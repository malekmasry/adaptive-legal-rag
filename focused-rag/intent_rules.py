    contract=bool(re.search(r'договор|аренд|пт[- /]*05|п[- /]*17|а[- /]*08|постав|товар|парти',q))
    add('rent_price',re.search(r'аренд|склад',q) and (re.search(r'коммунальн|электрич|сколько\s+стоит|месячн\w*\s+плат|какова[^.!?]{0,40}плат|размер\w*\s+арендн',q)))
